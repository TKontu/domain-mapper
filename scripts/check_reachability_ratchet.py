#!/usr/bin/env python3
"""Shrink-only module reachability ratchet (GV-02).

A public top-level symbol in ``core/``, ``adapters/`` or ``app/`` (a
module-level ``def``, ``async def``, ``class`` or simple-name assignment whose
name does not start with ``_``) must have a production reference: an
``ast.Name`` load or ``ast.Attribute`` attr equal to its name, or an import
naming it, in ``core/``, ``adapters/``, ``app/`` or ``scripts/``. References
from ``tests/`` do not count, and names listed only in a module's ``__all__``
do not count. Entry points named in ``pyproject.toml`` ``[project.scripts]``
count as referenced. Every currently unreferenced symbol is allowlisted in
``tests/fixtures/reachability_ratchet.toml`` as
``"<file>::<name>" = "<reason or row id>"``; a new unreferenced symbol or a
stale entry fails. Matching is name-based and deliberately coarse.
``--print`` emits the current unreferenced set as TOML.
"""

from __future__ import annotations

import argparse
import ast
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ALLOWLIST = ROOT / "tests" / "fixtures" / "reachability_ratchet.toml"
PACKAGES = ("core", "adapters", "app")
PRODUCTION = (*PACKAGES, "scripts")
SEED_REASON = "unwired at seed (GV-02)"

Entries = dict[str, str]


def _python_files(root: Path, package: str) -> list[Path]:
    return sorted((root / package).rglob("*.py"))


def public_symbols(path: Path) -> set[str]:
    """Module-level public names defined in ``path``."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            if not node.name.startswith("_"):
                names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(
                t.id
                for t in node.targets
                if isinstance(t, ast.Name) and not t.id.startswith("_")
            )
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if not node.target.id.startswith("_"):
                names.add(node.target.id)
    return names


def references(path: Path) -> set[str]:
    """Names referenced anywhere in ``path`` (name-based, deliberately coarse)."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
            names.add(node.id)
        elif isinstance(node, ast.Attribute):
            names.add(node.attr)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                names.add(alias.asname or alias.name.split(".")[-1])
        elif isinstance(node, ast.ImportFrom):
            names.update(alias.asname or alias.name for alias in node.names if alias.name != "*")
    return names


def entry_point_names(root: Path) -> set[str]:
    """Symbol names installed as console scripts in ``[project.scripts]``."""
    pyproject = root / "pyproject.toml"
    if not pyproject.exists():
        return set()
    data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    names: set[str] = set()
    for target in data.get("project", {}).get("scripts", {}).values():
        _, _, symbol = str(target).partition(":")
        symbol = symbol.strip()
        if symbol:
            names.add(symbol.rsplit(".", 1)[-1])
    return names


def scan(root: Path) -> set[str]:
    """The current unreferenced public symbols as ``"<file>::<name>"`` keys."""
    referenced: set[str] = set()
    for package in PRODUCTION:
        for path in _python_files(root, package):
            referenced |= references(path)
    referenced |= entry_point_names(root)

    unreferenced: set[str] = set()
    for package in PACKAGES:
        for path in _python_files(root, package):
            rel = path.relative_to(root).as_posix()
            for name in public_symbols(path):
                if name not in referenced:
                    unreferenced.add(f"{rel}::{name}")
    return unreferenced


def load_allowlist(path: Path) -> Entries:
    if not path.exists():
        return {}
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    return {str(k): str(v) for k, v in data.items()}


def to_toml(entries: set[str], reasons: Entries) -> str:
    lines = ["# Generated by scripts/check_reachability_ratchet.py --print", ""]
    for key in sorted(entries):
        reason = reasons.get(key, SEED_REASON).replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'"{key}" = "{reason}"')
    return "\n".join(lines) + "\n"


def compare(actual: set[str], allowed: Entries) -> list[str]:
    errors = []
    for key in sorted(actual - set(allowed)):
        path, name = key.split("::", 1)
        errors.append(
            f"{path}: {name} has no production reference; add a caller or an allowlist "
            f"entry naming the row that wires it"
        )
    for key in sorted(set(allowed) - actual):
        path, name = key.split("::", 1)
        errors.append(
            f"{path}: {name} is a stale allowlist entry (now referenced, private or gone); "
            f"remove it"
        )
    return errors


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root", type=Path, default=ROOT)
    p.add_argument("--allowlist", type=Path, default=DEFAULT_ALLOWLIST)
    p.add_argument("--print", action="store_true", dest="print_")
    args = p.parse_args(argv)
    actual = scan(args.root)
    if args.print_:
        sys.stdout.write(to_toml(actual, load_allowlist(args.allowlist)))
        return 0
    errors = compare(actual, load_allowlist(args.allowlist))
    for e in errors:
        print(e)
    if errors:
        print(f"reachability ratchet: {len(errors)} problem(s)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
