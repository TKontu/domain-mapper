#!/usr/bin/env python3
"""Shrink-only import-direction ratchet (GV-01).

Banned directions: ``core -> adapters`` and ``adapters -> core``. For each
(file, target package) the number of absolute ``import X...`` /
``from X... import`` statements, counted separately at module level and
function-local (any nested scope), must equal the allowlist entry in
``tests/fixtures/import_direction_ratchet.toml`` (missing entry = 0). A count
above the entry is a new violation; below it is a stale entry that must be
lowered. ``--print`` emits the current counts as TOML.
"""

from __future__ import annotations

import argparse
import ast
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ALLOWLIST = ROOT / "tests" / "fixtures" / "import_direction_ratchet.toml"
BANNED = {"core": "adapters", "adapters": "core"}

Counts = dict[tuple[str, str], dict[str, int]]


def _hits(name: str | None, target: str) -> bool:
    return name is not None and (name == target or name.startswith(target + "."))


def _count_file(path: Path, target: str) -> dict[str, int]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    out = {"module": 0, "local": 0}

    def visit(node: ast.AST, local: bool) -> None:
        for child in ast.iter_child_nodes(node):
            hit = False
            if isinstance(child, ast.Import):
                hit = any(_hits(a.name, target) for a in child.names)
            elif isinstance(child, ast.ImportFrom):
                hit = child.level == 0 and _hits(child.module, target)
            if hit:
                out["local" if local else "module"] += 1
            nested = isinstance(child, ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda)
            visit(child, local or nested)

    visit(tree, False)
    return out


def scan(root: Path) -> Counts:
    counts: Counts = {}
    for pkg, target in BANNED.items():
        for path in sorted((root / pkg).rglob("*.py")):
            c = _count_file(path, target)
            if c["module"] or c["local"]:
                counts[(path.relative_to(root).as_posix(), target)] = c
    return counts


def load_allowlist(path: Path) -> Counts:
    data = tomllib.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    return {
        (f, t): {"module": int(v.get("module", 0)), "local": int(v.get("local", 0))}
        for f, targets in data.items()
        for t, v in targets.items()
    }


def to_toml(counts: Counts) -> str:
    lines = ["# Generated by scripts/check_import_direction_ratchet.py --print", ""]
    for (f, t), c in sorted(counts.items()):
        lines += [f'["{f}".{t}]', f"module = {c['module']}", f"local = {c['local']}", ""]
    return "\n".join(lines)


def compare(actual: Counts, allowed: Counts) -> list[str]:
    errors = []
    zero = {"module": 0, "local": 0}
    for key in sorted(set(actual) | set(allowed)):
        f, t = key
        direction = f"{f.split('/', 1)[0]} -> {t}"
        a, al = actual.get(key, zero), allowed.get(key, zero)
        for scope in ("module", "local"):
            if a[scope] > al[scope]:
                errors.append(
                    f"{f}: new {direction} import ({scope}: {a[scope]} > allowed {al[scope]})"
                )
            elif a[scope] < al[scope]:
                errors.append(
                    f"{f}: stale allowlist entry for {direction} "
                    f"({scope}: {a[scope]} < allowed {al[scope]}); lower it"
                )
    return errors


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root", type=Path, default=ROOT)
    p.add_argument("--allowlist", type=Path, default=DEFAULT_ALLOWLIST)
    p.add_argument("--print", action="store_true", dest="print_")
    args = p.parse_args(argv)
    actual = scan(args.root)
    if args.print_:
        sys.stdout.write(to_toml(actual))
        return 0
    errors = compare(actual, load_allowlist(args.allowlist))
    for e in errors:
        print(e)
    if errors:
        print(f"import-direction ratchet: {len(errors)} problem(s)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
